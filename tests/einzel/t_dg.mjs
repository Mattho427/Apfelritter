import { chromium, ROOT, OUT, GAME, PAGE, MOBILE } from '../pfad.mjs';
const id = process.argv[2] || 'krypta', lvl = +(process.argv[3] || 8);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1000, height: 1000 } });
await ctx.addInitScript(() => { window.__season = 1; window.__wx = 'klar'; });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push('PAGEERROR ' + e.message + ' ' + (e.stack || '').split('\n').slice(1, 3).join(' ')));
await p.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
await p.goto(GAME, { waitUntil: 'load' });
await p.waitForTimeout(400);
await p.fill('#heroName', 'Test'); await p.press('#heroName', 'Enter');
await p.waitForTimeout(300);
const c = await p.$('#game');
console.log('doors', await p.evaluate(() => JSON.stringify(DG_DOORS)));
await p.evaluate(([id, lvl]) => { HERO.lvl = lvl; refreshStats(); G.knight.hp = ST.hp; window.__skyShift = 12 / 24 * DAY_LEN - (Date.now() / 1000 % DAY_LEN); const d = DG_DOORS.find(d => d.dg === id); G.knight.x = d.x; G.knight.y = d.y + 30; $('banner').hidden = true; }, [id, lvl]);
await p.waitForTimeout(800);
await c.screenshot({ path: 'd_door_' + id + '.png' });
await p.keyboard.press('KeyE');
await p.waitForTimeout(900);
await c.screenshot({ path: 'd_in_' + id + '.png' });
console.log(await p.evaluate(() => JSON.stringify({ on: !!DG_ON, mons: G.mons.map(m => m.k + m.lvl + (m.elite ? '*' : '')).join(' '), k: [Math.round(G.knight.x), Math.round(G.knight.y)], objs: DG_ON && DG_ON.objs.length, segs: DG_ON && DG_ON.segs.length, chest: DG_ON && !!DG_ON.chest })));
// zur Truhe springen und den Anführer erledigen
await p.evaluate(() => { const M = DG_ON, o = M.chest; G.knight.x = o.x; G.knight.y = o.y + 60; G.knight.dir = 'up'; for (const m of G.mons) if (!m.elite) m.mode = 'idle'; });
await p.waitForTimeout(1000);
await c.screenshot({ path: 'd_vault_' + id + '.png' });
await p.evaluate(() => { const e = G.mons.find(m => m.elite); if (e){ e.hp = 1; damage(e, 5, false, 1); } });
await p.waitForTimeout(600);
await p.evaluate(() => { const o = DG_ON.chest; G.knight.x = o.x; G.knight.y = o.y + 30; });
await p.waitForTimeout(300);
await p.keyboard.press('KeyE');
await p.waitForTimeout(1200);
await c.screenshot({ path: 'd_chest_' + id + '.png' });
console.log(await p.evaluate(() => JSON.stringify({ open: DG_ON.chestOpen, loot: G.loot.map(a => a.t + (a.it ? ':' + a.it.n : a.n)).join(', '), dg: HERO.dg })));
// zurück zur Treppe und hinauf
await p.evaluate(() => { G.knight.x = DG_ON.stair.x; G.knight.y = DG_ON.stair.y + 30; });
await p.waitForTimeout(300);
await p.keyboard.press('KeyE');
await p.waitForTimeout(500);
console.log(await p.evaluate(() => JSON.stringify({ on: !!DG_ON, zone: G.zone, k: [Math.round(G.knight.x), Math.round(G.knight.y)], mons: G.mons.length })));
await c.screenshot({ path: 'd_out_' + id + '.png' });
console.log(errs.join('\n') || 'ok');
await browser.close();
